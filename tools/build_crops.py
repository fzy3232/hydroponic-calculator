# -*- coding: utf-8 -*-
"""
生成 data/crops.csv：作物 × 生育期 → 目标元素浓度（mg/L）

数据来源（全部为公开文献，逐行标注在"来源"列；未找到可靠来源的作物一律不编造）：
  [A] Hoagland & Arnon (1938/1950) —— 由公开配方的肥料用量反算，数值已与教科书经典值核对通过
  [B] 日本园试配方（園芸試験場標準処方, 1960）—— 由公开肥料用量反算
  [C] 山崎配方（1976）—— 原文 me/L 换算（N14.0 P10.3 K39.1 Ca20.0 Mg12.2 S16.0）
  [D] 雅典农业大学（AUA）《ΕΙΔΙΚΗ ΥΔΡΟΠΟΝΙΑ》配方表 7.1–7.12 —— mmol/L/µmol/L 原值换算
      （NO3 14, NH4 14, P 31, K 39.1, Ca 40.08, Mg 24.3, S 32.06）
  [E] SARE(USDA) 养分液课程 —— 生菜 4 配方
  [F] IARI（印度农业研究所）水培技术公报 —— 标准液

注意：不同体系（如山崎 vs AUA）的绝对值差异很大，不可混用；同一配方内保持一致。
"""
import csv, os

# 脚本已归档到 tools/，所以项目根（含 data/）在上一级
HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(HERE)
ELEMS = ['NO3-N', 'NH4-N', 'P', 'K', 'Ca', 'Mg', 'S',
         'Fe', 'Mn', 'Zn', 'Cu', 'B', 'Mo', 'Si', 'Na', 'Cl']

with open(os.path.join(PROJECT_DIR, 'data', 'fertilizers.csv'), encoding='utf-8-sig') as f:
    FERTS = {r['名称']: {e: float(r[e] or 0) for e in ELEMS} for r in csv.DictReader(f)}


def from_salts(amounts, micro=None):
    """由公开配方的肥料用量(g/1000L)反算元素浓度(mg/L)"""
    comp = {e: 0.0 for e in ELEMS}
    for name, grams in amounts.items():
        if name not in FERTS:
            raise KeyError('肥料库中缺少：' + name)
        for e in ELEMS:
            comp[e] += grams * FERTS[name][e] / 100.0
    if micro:
        comp.update(micro)
    return {e: round(comp[e], 3) for e in ELEMS}


ROWS = []


def row(crop, stage, vals, ec, ph, src, note=''):
    t = {e: 0.0 for e in ELEMS}
    t.update(vals)
    r = {'作物': crop, '生育期': stage}
    r.update({e: round(t[e], 3) for e in ELEMS})
    r.update({'EC目标': ec, 'pH下限': ph[0], 'pH上限': ph[1], '备注': note, '来源': src})
    ROWS.append(r)


