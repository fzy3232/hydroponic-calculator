row('通用配方', 'Hoagland 全浓度', from_salts(HOAG, MICRO_HOAG), '2.0–2.4', ('5.5', '6.0'),
    'Hoagland & Arnon 1938（反算）', '最经典通用全营养液；数值已与教科书经典值核对通过')
